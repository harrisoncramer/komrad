//go:build ignore

// Command gen writes approved.go from every octicon in the Private Use Area of the pinned copy
// of Nerd Fonts' glyphnames.json.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	inputPath       = "nerdfonts/glyphnames.json"
	outputPath      = "approved.go"
	prefix          = "oct-"
	privateUseStart = 0xe000
	privateUseEnd   = 0xf8ff
)

type entry struct {
	Code string `json:"code"`
}

type octicon struct {
	name  string
	point int64
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "failed to generate %s: %v\n", outputPath, err)
		os.Exit(1)
	}

	fmt.Printf("wrote %s\n", outputPath)
}

func run() error {
	raw, err := os.ReadFile(inputPath)
	if err != nil {
		return err
	}

	var names map[string]json.RawMessage
	if err := json.Unmarshal(raw, &names); err != nil {
		return err
	}

	var metadata struct {
		Version string `json:"version"`
	}
	if err := json.Unmarshal(names["METADATA"], &metadata); err != nil {
		return fmt.Errorf("failed to read METADATA: %w", err)
	}

	var octicons []octicon
	for name, value := range names {
		if !strings.HasPrefix(name, prefix) {
			continue
		}

		var e entry
		if err := json.Unmarshal(value, &e); err != nil {
			return fmt.Errorf("failed to read %s: %w", name, err)
		}

		point, err := strconv.ParseInt(e.Code, 16, 32)
		if err != nil {
			return fmt.Errorf("failed to read the code point of %s: %w", name, err)
		}

		if point < privateUseStart || point > privateUseEnd {
			continue
		}

		octicons = append(octicons, octicon{name: strings.TrimPrefix(name, prefix), point: point})
	}

	sort.Slice(octicons, func(i, j int) bool {
		if octicons[i].point != octicons[j].point {
			return octicons[i].point < octicons[j].point
		}

		return octicons[i].name < octicons[j].name
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by gen/main.go from nerdfonts/glyphnames.json. DO NOT EDIT.\n\n")
	b.WriteString("package glyph\n\n")
	fmt.Fprintf(&b, "// NerdFontsVersion is the Nerd Fonts release the octicons were read from.\n")
	fmt.Fprintf(&b, "const NerdFontsVersion = %q\n\n", metadata.Version)
	b.WriteString("// octicons is every octicon in that release in the Private Use Area, by code point.\n")
	b.WriteString("var octicons = []Character{\n")
	for _, o := range octicons {
		fmt.Fprintf(&b, "\t{Rune: 0x%x, Name: %q},\n", o.point, prefix+o.name)
	}
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	return os.WriteFile(outputPath, formatted, 0o644)
}
