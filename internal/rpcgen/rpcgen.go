// Package rpcgen writes the strict handler interface and the adapter for each service, which is
// what keeps a failure's code decided by its type rather than by whoever wrote the handler.
//
// A unary method answers with a message and a failure. A streaming method receives its stream
// and answers with a failure alone. The generator refuses a method that streams only from the client.
//
// A request whose protovalidate rules describe values with a Go type of their own reaches the
// implementation parsed, and a request holding a value that would not convert is refused as an
// invalid argument before the implementation sees it.
//
// A oneof holding no message reaches the implementation as the type named for it in the oneofs
// package, one type for every oneof with that name, which a service takes without knowing the
// request it came in.
package rpcgen

import (
	"fmt"
	"path"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"

	"komrad/lib/protoconv/generate"
)

// packageSuffix names the package the generated half of a service lives in.
const packageSuffix = "komrad"

// parsedFile names the file in each generated package holding the parsed requests.
const parsedFile = "parsed.komrad.go"

// The package the shared types of oneofs live in, and the file holding them.
const (
	oneofsPackage = protogen.GoImportPath("komrad/proto/gen/oneofs")
	oneofsFile    = "oneofs/oneofs.komrad.go"
)

// The packages the generated code leans on, which are komrad's own rather than connect's.
const (
	connectPackage = protogen.GoImportPath("connectrpc.com/connect")
	failPackage    = protogen.GoImportPath("komrad/internal/fail")
	rpcerrPackage  = protogen.GoImportPath("komrad/internal/rpcerr")
	contextPackage = protogen.GoImportPath("context")
	httpPackage    = protogen.GoImportPath("net/http")
)

// parsedPackage is the file of one generated package that holds its parsed requests.
type parsedPackage struct {
	out       *protogen.GeneratedFile
	path      protogen.GoImportPath
	generator *generate.Generator
	written   bool
}

// request is how a method's implementation receives what the caller sent.
type request struct {
	raw    string
	parsed string
	parse  string
}

// Generate writes one file per proto file that declares a service, and the parsed requests of
// each generated package.
func Generate(plugin *protogen.Plugin) error {
	plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL |
		pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
	plugin.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO2
	plugin.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2023

	run := &generation{
		plugin:   plugin,
		packages: map[protogen.GoImportPath]*parsedPackage{},
		shared:   generate.NewShared(oneofsPackage),
	}
	for _, file := range plugin.Files {
		if !file.Generate || len(file.Services) == 0 {
			continue
		}

		if err := run.generateFile(file); err != nil {
			return err
		}
	}

	for _, parsed := range run.packages {
		if !parsed.written {
			parsed.out.Skip()
		}
	}

	oneofs := plugin.NewGeneratedFile(oneofsFile, oneofsPackage)
	oneofs.P("// Code generated by protoc-gen-komrad-rpc. DO NOT EDIT.")
	oneofs.P()
	oneofs.P("// Package oneofs holds the types oneofs reach a service as.")
	oneofs.P("package oneofs")
	oneofs.P()
	if !run.shared.Write(oneofs) {
		oneofs.Skip()
	}

	return nil
}

// generation is one run of the plugin: the parsed requests of each generated package and the
// types oneofs share across them.
type generation struct {
	plugin   *protogen.Plugin
	packages map[protogen.GoImportPath]*parsedPackage
	shared   *generate.Shared
}

// generateFile writes the strict interface, adapter and register function for every service in one proto file.
func (g *generation) generateFile(file *protogen.File) error {
	for _, service := range file.Services {
		for _, method := range service.Methods {
			if method.Desc.IsStreamingClient() && !method.Desc.IsStreamingServer() {
				return fmt.Errorf("%s.%s streams only from the client, which nothing in komrad serves", service.GoName, method.GoName)
			}
		}
	}

	pkg := string(file.GoPackageName) + packageSuffix
	dir := path.Join(path.Dir(file.GeneratedFilenamePrefix), pkg)
	importPath := protogen.GoImportPath(path.Join(string(file.GoImportPath), pkg))
	out := g.plugin.NewGeneratedFile(path.Join(dir, path.Base(file.GeneratedFilenamePrefix)+".komrad.go"), importPath)
	writeHeader(out, file, pkg)

	parsed, ok := g.packages[importPath]
	if !ok {
		parsedOut := g.plugin.NewGeneratedFile(path.Join(dir, parsedFile), importPath)
		writeHeader(parsedOut, file, pkg)
		parsed = &parsedPackage{
			out:       parsedOut,
			path:      importPath,
			generator: generate.New(parsedOut, importPath, g.shared),
		}
		g.packages[importPath] = parsed
	}

	handlerPackage := protogen.GoImportPath(path.Join(string(file.GoImportPath), string(file.GoPackageName)+"connect"))
	for _, service := range file.Services {
		if err := generateService(out, service, handlerPackage, parsed); err != nil {
			return err
		}
	}

	return nil
}

// writeHeader opens a generated file of package pkg.
func writeHeader(out *protogen.GeneratedFile, file *protogen.File, pkg string) {
	out.P("// Code generated by protoc-gen-komrad-rpc. DO NOT EDIT.")
	out.P("//")
	out.P("// Source: ", file.Desc.Path())
	out.P()
	out.P("package ", pkg)
	out.P()
}

// requestOf writes the parsed form of a method's request when it has one, and says how the
// implementation receives it.
func (p *parsedPackage) requestOf(out *protogen.GeneratedFile, method *protogen.Method) (request, error) {
	raw := out.QualifiedGoIdent(method.Input.GoIdent)
	wrote, err := p.generator.Write(method.Input)
	if err != nil {
		return request{}, fmt.Errorf("failed to parse the request of %s: %w", method.Desc.FullName(), err)
	}

	if !wrote {
		return request{raw: raw, parsed: raw}, nil
	}

	p.written = true
	name := method.Input.GoIdent.GoName

	return request{
		raw:    raw,
		parsed: out.QualifiedGoIdent(p.path.Ident(name)),
		parse:  out.QualifiedGoIdent(p.path.Ident("Parse" + name)),
	}, nil
}

// generateService writes one service's strict interface, the adapter that answers for it, and its register function.
func generateService(
	out *protogen.GeneratedFile,
	service *protogen.Service,
	handlerPackage protogen.GoImportPath,
	parsed *parsedPackage,
) error {
	requests := make([]request, len(service.Methods))
	for index, method := range service.Methods {
		found, err := parsed.requestOf(out, method)
		if err != nil {
			return err
		}
		requests[index] = found
	}

	name := service.GoName
	context := out.QualifiedGoIdent(contextPackage.Ident("Context"))
	failure := out.QualifiedGoIdent(failPackage.Ident("Error"))

	serverStream := out.QualifiedGoIdent(connectPackage.Ident("ServerStream"))
	bidiStream := out.QualifiedGoIdent(connectPackage.Ident("BidiStream"))

	out.P("// ", name, "Impl is the half of ", name, " a person writes, whose failures carry the kind")
	out.P("// of failure they are rather than leaving it to be decided later.")
	out.P("type ", name, "Impl interface {")
	for index, method := range service.Methods {
		input := requests[index]
		output := out.QualifiedGoIdent(method.Output.GoIdent)
		if method.Desc.IsStreamingClient() {
			if input.parse != "" {
				out.P(method.GoName, "(", context, ", *", method.GoName, "Stream) *", failure)

				continue
			}

			out.P(method.GoName, "(", context, ", *", bidiStream, "[", input.raw, ", ", output, "]) *", failure)

			continue
		}

		if method.Desc.IsStreamingServer() {
			out.P(method.GoName, "(", context, ", *", input.parsed, ", *", serverStream, "[", output, "]) *", failure)

			continue
		}

		out.P(method.GoName, "(", context, ", *", input.parsed, ") (*", output, ", *", failure, ")")
	}
	out.P("}")
	out.P()

	out.P("// ", name, "Adapter carries what the implementation returned across to the signature")
	out.P("// connect fixed, and is what gets registered rather than the implementation itself.")
	out.P("type ", name, "Adapter struct {")
	out.P("Impl ", name, "Impl")
	out.P("}")
	out.P()

	answer := out.QualifiedGoIdent(rpcerrPackage.Ident("Answer"))
	answerStream := out.QualifiedGoIdent(rpcerrPackage.Ident("AnswerStream"))
	unparsed := out.QualifiedGoIdent(rpcerrPackage.Ident("Unparsed"))
	connectRequest := out.QualifiedGoIdent(connectPackage.Ident("Request"))
	response := out.QualifiedGoIdent(connectPackage.Ident("Response"))

	for index, method := range service.Methods {
		input := requests[index]
		output := out.QualifiedGoIdent(method.Output.GoIdent)

		if method.Desc.IsStreamingClient() {
			out.P("// ", method.GoName, " serves the stream as connect opens it.")
			out.P("func (a ", name, "Adapter) ", method.GoName, "(ctx ", context, ", stream *", bidiStream, "[", input.raw, ", ", output, "]) error {")
			if input.parse != "" {
				out.P("return ", answerStream, "(a.Impl.", method.GoName, "(ctx, &", method.GoName, "Stream{stream: stream}))")
			} else {
				out.P("return ", answerStream, "(a.Impl.", method.GoName, "(ctx, stream))")
			}
			out.P("}")
			out.P()

			if input.parse != "" {
				writeStream(out, method, input)
			}

			continue
		}

		if method.Desc.IsStreamingServer() {
			out.P("// ", method.GoName, " serves the stream as connect opens it.")
			out.P("func (a ", name, "Adapter) ", method.GoName, "(ctx ", context, ", req *", connectRequest, "[", input.raw,
				"], stream *", serverStream, "[", output, "]) error {")
			if input.parse != "" {
				out.P("parsed, err := ", input.parse, "(req.Msg)")
				out.P("if err != nil {")
				out.P("return ", answerStream, "(", unparsed, "(err))")
				out.P("}")
				out.P()
				out.P("return ", answerStream, "(a.Impl.", method.GoName, "(ctx, parsed, stream))")
			} else {
				out.P("return ", answerStream, "(a.Impl.", method.GoName, "(ctx, req.Msg, stream))")
			}
			out.P("}")
			out.P()

			continue
		}

		out.P("// ", method.GoName, " answers the request as connect serves it.")
		out.P("func (a ", name, "Adapter) ", method.GoName, "(ctx ", context, ", req *", connectRequest, "[", input.raw,
			"]) (*", response, "[", output, "], error) {")
		if input.parse != "" {
			out.P("parsed, err := ", input.parse, "(req.Msg)")
			out.P("if err != nil {")
			out.P("return ", answer, "[", output, "](nil, ", unparsed, "(err))")
			out.P("}")
			out.P()
			out.P("return ", answer, "(a.Impl.", method.GoName, "(ctx, parsed))")
		} else {
			out.P("return ", answer, "(a.Impl.", method.GoName, "(ctx, req.Msg))")
		}
		out.P("}")
		out.P()
	}

	mux := out.QualifiedGoIdent(httpPackage.Ident("ServeMux"))
	option := out.QualifiedGoIdent(connectPackage.Ident("HandlerOption"))
	newHandler := out.QualifiedGoIdent(handlerPackage.Ident("New" + name + "Handler"))

	out.P("// Register", name, " mounts the implementation on the mux behind its adapter.")
	out.P("func Register", name, "(mux *", mux, ", impl ", name, "Impl, options ...", option, ") {")
	out.P("mux.Handle(", newHandler, "(", name, "Adapter{Impl: impl}, options...))")
	out.P("}")
	out.P()

	return nil
}

// writeStream writes the stream a bidirectional method's implementation serves, which hands over
// each message it receives parsed.
func writeStream(out *protogen.GeneratedFile, method *protogen.Method, input request) {
	name := method.GoName + "Stream"
	output := out.QualifiedGoIdent(method.Output.GoIdent)
	bidiStream := out.QualifiedGoIdent(connectPackage.Ident("BidiStream"))
	newError := out.QualifiedGoIdent(rpcerrPackage.Ident("New"))
	invalid := out.QualifiedGoIdent(failPackage.Ident("KindInvalidArgument"))

	out.P("// ", name, " is the stream ", method.GoName, " serves, handing over each message it receives parsed.")
	out.P("type ", name, " struct {")
	out.P("stream *", bidiStream, "[", input.raw, ", ", output, "]")
	out.P("}")
	out.P()
	out.P("// Receive reads the next message, refusing one holding a value that would not convert.")
	out.P("func (s *", name, ") Receive() (*", input.parsed, ", error) {")
	out.P("message, err := s.stream.Receive()")
	out.P("if err != nil {")
	out.P("return nil, err")
	out.P("}")
	out.P()
	out.P("parsed, err := ", input.parse, "(message)")
	out.P("if err != nil {")
	out.P("return nil, ", newError, "(", invalid, ", err)")
	out.P("}")
	out.P()
	out.P("return parsed, nil")
	out.P("}")
	out.P()
	out.P("// Send writes a message to the caller.")
	out.P("func (s *", name, ") Send(message *", output, ") error {")
	out.P("return s.stream.Send(message)")
	out.P("}")
	out.P()
}
