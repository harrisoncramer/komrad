package triggers

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"komrad/db/isolation"
	"komrad/db/migrator"
	"komrad/internal/fail"
)

const fingerprintLength = 12

const header = "-- Code generated by mise run gen:triggers. DO NOT EDIT.\n-- fingerprint: "

//go:embed templates/*.tmpl
var templateFS embed.FS

var templates = template.Must(template.New("").Funcs(template.FuncMap{
	"args":               quoteAll,
	"names":              triggerNames,
	"stampEngineTrigger": func() string { return isolation.StampEngineTrigger },
}).ParseFS(templateFS, "templates/*.tmpl"))

var (
	identifier = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)
	timings    = []string{"BEFORE", "AFTER"}
	events     = []string{"INSERT", "UPDATE", "DELETE"}
)

var errNoFingerprint = fail.Precondition("the file has no fingerprint header")

// unit is one file's worth of trigger SQL, applied as a whole.
type unit struct {
	Name string
	SQL  string
}

type existingFile struct {
	name        string
	version     int
	fingerprint string
}

// render writes the SQL for every unit, the functions first and then each table by name.
func render() ([]unit, error) {
	tables := tables()
	functions := listFunctions()
	if err := validateFunctions(functions); err != nil {
		return nil, err
	}
	if err := validateTables(tables, functions); err != nil {
		return nil, err
	}

	var functionsSQL bytes.Buffer
	if err := templates.ExecuteTemplate(&functionsSQL, "functions.sql.tmpl", functions); err != nil {
		return nil, fmt.Errorf("failed to render the trigger functions: %w", err)
	}
	units := []unit{{Name: migrator.TriggerFunctionsUnit, SQL: functionsSQL.String()}}

	for _, table := range tables {
		var tableSQL bytes.Buffer
		if err := templates.ExecuteTemplate(&tableSQL, "table.sql.tmpl", table); err != nil {
			return nil, fmt.Errorf("failed to render the triggers on %s: %w", table.Name, err)
		}
		units = append(units, unit{Name: table.Name, SQL: tableSQL.String()})
	}

	return units, nil
}

func validateFunctions(functions []triggerFunction) error {
	seen := map[string]bool{}
	for _, function := range functions {
		if !identifier.MatchString(function.Name) {
			return fmt.Errorf("function name %q is not a plain identifier", function.Name)
		}
		if seen[function.Name] {
			return fmt.Errorf("function %s is declared twice", function.Name)
		}
		if strings.Contains(function.Body, "$$") {
			return fmt.Errorf("function %s has $$ in its body", function.Name)
		}
		seen[function.Name] = true
	}

	return nil
}

func validateTables(tables []triggeredTable, functions []triggerFunction) error {
	declaredFunctions := map[string]bool{}
	for _, function := range functions {
		declaredFunctions[function.Name] = true
	}

	seenTables := map[string]bool{}
	for _, table := range tables {
		if !identifier.MatchString(table.Name) || table.Name == migrator.TriggerFunctionsUnit {
			return fmt.Errorf("table name %q is not a plain identifier", table.Name)
		}
		if seenTables[table.Name] {
			return fmt.Errorf("table %s is declared twice", table.Name)
		}
		seenTables[table.Name] = true

		seenTriggers := map[string]bool{}
		for _, trigger := range table.Triggers {
			if seenTriggers[trigger.Name] {
				return fmt.Errorf("trigger %s is declared twice on %s", trigger.Name, table.Name)
			}
			seenTriggers[trigger.Name] = true
			if err := validateTrigger(table.Name, trigger, declaredFunctions); err != nil {
				return err
			}
		}
	}

	return nil
}

func validateTrigger(table string, trigger rowTrigger, declaredFunctions map[string]bool) error {
	if !identifier.MatchString(trigger.Name) {
		return fmt.Errorf("trigger name %q on %s is not a plain identifier", trigger.Name, table)
	}
	if !slices.Contains(timings, trigger.Timing) {
		return fmt.Errorf("trigger %s on %s has timing %q", trigger.Name, table, trigger.Timing)
	}
	for event := range strings.SplitSeq(trigger.Events, " OR ") {
		if !slices.Contains(events, event) {
			return fmt.Errorf("trigger %s on %s has event %q", trigger.Name, table, event)
		}
	}
	if !declaredFunctions[trigger.Function] {
		return fmt.Errorf("trigger %s on %s runs undeclared function %s", trigger.Name, table, trigger.Function)
	}

	return nil
}

func quoteAll(values []string) string {
	quoted := make([]string, len(values))
	for i, value := range values {
		quoted[i] = "'" + strings.ReplaceAll(value, "'", "''") + "'"
	}

	return strings.Join(quoted, ", ")
}

func triggerNames(triggers []rowTrigger) string {
	names := make([]string, len(triggers))
	for i, trigger := range triggers {
		names[i] = trigger.Name
	}

	return quoteAll(names)
}

func fingerprintOf(sql string) string {
	sum := sha256.Sum256([]byte(sql))

	return hex.EncodeToString(sum[:])[:fingerprintLength]
}

// Sync rewrites dir to hold one file per unit, bumping a unit's version whenever its SQL changes.
func Sync(dir string) error {
	units, err := render()
	if err != nil {
		return err
	}

	existing, err := readExisting(dir)
	if err != nil {
		return err
	}

	for _, unit := range units {
		fingerprint := fingerprintOf(unit.SQL)
		version := 1
		if file, ok := existing[unit.Name]; ok {
			version = file.version
			if file.fingerprint != fingerprint {
				version++
				if err := os.Remove(filepath.Join(dir, file.name)); err != nil {
					return fmt.Errorf("failed to remove %s: %w", file.name, err)
				}
			}
			delete(existing, unit.Name)
		}

		name := fmt.Sprintf("%s.v%d.sql", unit.Name, version)
		content := header + fingerprint + "\n" + unit.SQL
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return fmt.Errorf("failed to write %s: %w", name, err)
		}
	}

	for _, file := range existing {
		if err := os.Remove(filepath.Join(dir, file.name)); err != nil {
			return fmt.Errorf("failed to remove %s: %w", file.name, err)
		}
	}

	return nil
}

func readExisting(dir string) (map[string]existingFile, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("failed to create %s: %w", dir, err)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("failed to read %s: %w", dir, err)
	}

	existing := map[string]existingFile{}
	for _, entry := range entries {
		if !strings.HasSuffix(entry.Name(), ".sql") {
			continue
		}

		unit, version, err := migrator.ParseTriggerFileName(entry.Name())
		if err != nil {
			return nil, err
		}
		if other, ok := existing[unit]; ok {
			return nil, fmt.Errorf("unit %s has two files, %s and %s", unit, other.name, entry.Name())
		}

		content, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return nil, fmt.Errorf("failed to read %s: %w", entry.Name(), err)
		}
		fingerprint, err := readFingerprint(content)
		if err != nil {
			return nil, fmt.Errorf("failed to read the fingerprint of %s: %w", entry.Name(), err)
		}

		existing[unit] = existingFile{
			name:        entry.Name(),
			version:     version,
			fingerprint: fingerprint,
		}
	}

	return existing, nil
}

func readFingerprint(content []byte) (string, error) {
	rest, ok := bytes.CutPrefix(content, []byte(header))
	if !ok {
		return "", errNoFingerprint
	}

	fingerprint, _, ok := bytes.Cut(rest, []byte("\n"))
	if !ok {
		return "", errNoFingerprint
	}

	return string(fingerprint), nil
}
