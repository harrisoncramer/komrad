//go:build ignore

// Command gen writes the Go types of the test protos and their parsed forms.
package main

import (
	"context"
	"fmt"
	"os"
	"path/filepath"

	gengo "google.golang.org/protobuf/cmd/protoc-gen-go/internal_gengo"
	"google.golang.org/protobuf/compiler/protogen"

	"komrad/lib/protoconv/generate"
	"komrad/lib/protoconv/internal/prototest"
)

const (
	parsedPath = protogen.GoImportPath("komrad/lib/protoconv/internal/testparsed")
	parsedFile = "../testparsed/parsed.go"
)

var sourceFiles = []string{"shapes.proto", "editions.proto"}

func main() {
	if err := run(context.Background()); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(ctx context.Context) error {
	sources := map[string]string{}
	for _, name := range sourceFiles {
		content, err := os.ReadFile(name)
		if err != nil {
			return fmt.Errorf("failed to read %s: %w", name, err)
		}
		sources[name] = string(content)
	}

	plugin, err := prototest.Compile(ctx, sources)
	if err != nil {
		return err
	}

	out := plugin.NewGeneratedFile(parsedFile, parsedPath)
	out.P("// Code generated by komrad/lib/protoconv/internal/testpb/gen. DO NOT EDIT.")
	out.P()
	out.P("package testparsed")
	out.P()

	shared := generate.NewShared(parsedPath)
	generator := generate.New(out, parsedPath, shared)
	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}

		gengo.GenerateFile(plugin, file)
		for _, message := range allMessages(file.Messages) {
			if _, err := generator.Write(message); err != nil {
				return err
			}
		}
	}

	shared.Write(out)

	response := plugin.Response()
	if response.Error != nil {
		return fmt.Errorf("failed to generate: %s", response.GetError())
	}

	for _, file := range response.File {
		if err := os.WriteFile(filepath.FromSlash(file.GetName()), []byte(file.GetContent()), 0o644); err != nil {
			return fmt.Errorf("failed to write %s: %w", file.GetName(), err)
		}
	}

	return nil
}

func allMessages(messages []*protogen.Message) []*protogen.Message {
	var all []*protogen.Message
	for _, message := range messages {
		if message.Desc.IsMapEntry() {
			continue
		}
		all = append(all, message)
		all = append(all, allMessages(message.Messages)...)
	}

	return all
}
